# membership operators

# create a list of numbers
numbers = [10, 20, 30, 40, 50]
print(f"numbers = {numbers}")

print()

# in operator
print(f"is 50 present in numbers      = {50 in numbers}")
print(f"is 100 present in numbers     = {100 in numbers}")

print()

# not in operator (answer will be always opposite of in operator)
print(f"is 50 not present in numbers  = {50 not in numbers}")
print(f"is 100 not present in numbers = {100 not in numbers}")
