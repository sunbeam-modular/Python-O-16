# arithmetic operators
# - result depends upon the operands type

n1 = 5
n2 = 3

# arithmetic addition
print(f"{n1} + {n2} = {n1 + n2}")

# arithemtic subtraction
print(f"{n1} - {n2} = {n1 - n2}")

# arithmetic multiplication
print(f"{n1} * {n2} = {n1 * n2}")

# arithemtic (true) division
# - the result will be always a decimal (float) value
print(f"{n1} / {n2} = {n1 / n2}")

# arithemtic (floor) division
# - the result will be always a whole (int) value
print(f"{n1} // {n2} = {n1 // n2}")

# arithmetic modulous
# - returns the remainder of the division
print(f"{n1} % {n2} = {n1 % n2}")

# arithemtic exponent
print(f"{n1} ** {n2} = {n1 ** n2}")
