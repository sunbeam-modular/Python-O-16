# comparison operators
# - always returns boolean result (True/False)

n1 = 10
n2 = 5

print(f"{n1} > {n2}  = {n1 > n2}")
print(f"{n1} < {n2}  = {n1 < n2}")
print(f"{n1} == {n2} = {n1 == n2}")
print(f"{n1} != {n2} = {n1 != n2}")
print(f"{n1} >= {n2} = {n1 >= n2}")
print(f"{n1} <= {n2} = {n1 <= n2}")
